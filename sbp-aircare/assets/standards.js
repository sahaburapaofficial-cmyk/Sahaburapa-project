function tip(title, text) { return h('div', { class: 'sd-tip' }, h('b', {}, title), h('p', {}, text)); }

export function mountStandards(root, { start = 'clean' } = {}) {
  if (!root) return null;
  root.classList.add('sd');
  const tabs = h('div', { class: 'sd-tabs', role: 'tablist', 'aria-label': 'มาตรฐานงาน' });
  const panel = h('div', { class: 'sd-panel', role: 'tabpanel', id: 'sd-panel', tabindex: '0' });
  const set = id => {
    $$('[role=tab]', tabs).forEach(b => { const on = b.dataset.t === id; b.setAttribute('aria-selected', String(on)); b.tabIndex = on ? 0 : -1; });
    const t = TABS.find(x => x.id === id); panel.innerHTML = ''; panel.setAttribute('aria-labelledby', 'sd-t-' + id); panel.append(...t.body());
  };
  TABS.forEach(t => tabs.append(h('button', { type: 'button', role: 'tab', id: 'sd-t-' + t.id, 'aria-controls': 'sd-panel', 'data-t': t.id, onclick: () => set(t.id) }, t.th)));
  tabs.addEventListener('keydown', e => { if (!['ArrowRight', 'ArrowLeft'].includes(e.key)) return; const bs = $$('[role=tab]', tabs), i = bs.indexOf(document.activeElement); if (i < 0) return; const n = bs[(i + (e.key === 'ArrowRight' ? 1 : bs.length - 1)) % bs.length]; n.focus(); set(n.dataset.t); });
  root.append(tabs, panel);
  set(start);
  return { set };
}
